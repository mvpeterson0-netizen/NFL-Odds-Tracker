"""Turn signal_candidates.json into history rows for the admin-only Supabase table (supabase/014_signal_research.sql).
Writes seed_signal_research.sql to --out (NOT committed: research outputs stay private).
python -m research.signal_stacks.make_seed [--out DIR]"""
import argparse
import json
from pathlib import Path

MAP = {  # signal id -> [(market, family, condition, side)]
    "SP1": [("rec_yds", "spread", ">=+10", "under")], "SP2": [("rec", "spread", ">=+10", "under")],
    "SP3": [("pass_yds", "spread", "<=-10", "over")], "SP4": [("pass_yds", "spread", ">=+10", "under")],
    "SP5": [("rush_yds", "spread", "+3..+6.5", "under"), ("rush_yds:QB", "spread", "+3..+6.5", "under"), ("rush_yds:RB", "spread", "+3..+6.5", "under")],
    "WX1": [(m, "weather", "outdoor wind>=15", "under") for m in ("pass_yds", "rec", "rec_yds")],
    "WX2": [(m, "weather", "outdoor <55F (WX2 bucket)", "under") for m in ("rec", "rec_yds")],
}
SPREAD_NOTE = "Spread = nflverse schedule spread_line (post-hoc/closing-type). NOT a capture-time backtest."
WEATHER_NOTE = "Observed (post-game) weather, not a forecast. 2025 nflverse record; 2026 partly Open-Meteo observed. 2026 has no wind>=15 outdoor games in the sample."


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default="/home/claude/stix_research/out")
    out = Path(ap.parse_args().out)
    d = json.load(open(out / "signal_candidates.json"))
    cells = {(e["market"], e["family"], e["condition"], e["side"]): e for e in d["cells"]}
    rows = []
    for sid, specs in MAP.items():
        body = {"signal": sid, "family_size_for_q": d["family_size"], "cells": [],
                "note": SPREAD_NOTE if sid.startswith("SP") else WEATHER_NOTE,
                "status_reason": "Context/Testing only: no cell survives Benjamini-Hochberg across the whole candidate family at q<=0.05."}
        for spec in specs:
            e = cells.get(spec)
            if not e:
                continue
            body["cells"].append({k: e[k] for k in ("market", "condition", "side", "W", "L", "P", "hit", "roi", "units", "games", "props", "ci", "p", "bh_q",
                                                    "roi_flat_m110", "roi_shaded_5", "roi_ex_top3_games", "top_player_share_of_profit", "season_roi", "same_sign_both_seasons") if k in e})
        rows.append((f"history:{sid}", body))
    sql = ["-- Seed of Signal Stacks research history (admin-only). Generated by research/signal_stacks/make_seed.py; do not commit.",
           "insert into public.signal_research (id, kind, body) values"]
    sql.append(",\n".join("  ('%s', 'history', '%s'::jsonb)" % (i, json.dumps(b).replace("'", "''")) for i, b in rows))
    sql.append("on conflict (id) do update set body = excluded.body, updated_utc = now();")
    (out / "seed_signal_research.sql").write_text("\n".join(sql) + "\n")
    print(len(rows), "history rows")


if __name__ == "__main__":
    main()
